from decimal import Decimal
from django.db import models
from django.utils import timezone
from catalog.models import Client, Part


def today():
    """Return the current local date (not a datetime) for DateField defaults."""
    return timezone.localdate()


class Invoice(models.Model):
    """A sales invoice. Status is derived from payments, not set by hand."""

    class Status(models.TextChoices):
        PAID = "paid", "Payée"
        PARTIAL = "partial", "Partielle"
        UNPAID = "unpaid", "Impayée"

    number = models.CharField("numéro", max_length=20, unique=True, blank=True)
    client = models.ForeignKey(Client, on_delete=models.PROTECT, related_name="invoices")
    issue_date = models.DateField("date", default=today)
    due_date = models.DateField("échéance")
    notes = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    # ── Existing-invoice fields ──────────────────────────────────────────────
    is_existing  = models.BooleanField("facture existante", default=False)
    manual_total = models.DecimalField("montant total", max_digits=12, decimal_places=3, null=True, blank=True)
    manual_paid  = models.DecimalField("montant payé",  max_digits=12, decimal_places=3, null=True, blank=True)
    photo        = models.FileField("photo", upload_to="invoices/", null=True, blank=True)

    class Meta:
        ordering = ["-issue_date", "-id"]

    def __str__(self):
        return self.number or f"Facture #{self.pk}"

    def save(self, *args, **kwargs):
        if not self.number:
            last = Invoice.objects.order_by("-id").first()
            n = (int(last.number.replace("F-", "")) + 1) if last and last.number else 1042
            self.number = f"F-{n}"
        super().save(*args, **kwargs)

    @property
    def total(self):
        if self.is_existing and self.manual_total is not None:
            return self.manual_total
        return sum((line.subtotal for line in self.lines.all()), Decimal("0"))

    @property
    def amount_paid(self):
        if self.is_existing and self.manual_paid is not None:
            return self.manual_paid
        return sum((p.amount for p in self.payments.all()), Decimal("0"))

    @property
    def amount_due(self):
        return self.total - self.amount_paid

    @property
    def status(self):
        total, paid = self.total, self.amount_paid
        if total > 0 and paid >= total:
            return self.Status.PAID
        if paid > 0:
            return self.Status.PARTIAL
        return self.Status.UNPAID

    @property
    def is_overdue(self):
        return self.status != self.Status.PAID and self.due_date < today()

    @property
    def days_overdue(self):
        if not self.is_overdue:
            return 0
        return (today() - self.due_date).days


class InvoiceLine(models.Model):
    """A single line on an invoice. Optionally linked to a stock part."""
    invoice = models.ForeignKey(Invoice, on_delete=models.CASCADE, related_name="lines")
    part = models.ForeignKey(Part, on_delete=models.SET_NULL, null=True, blank=True)
    description = models.CharField("désignation", max_length=200)
    quantity = models.DecimalField("quantité", max_digits=10, decimal_places=2, default=1)
    unit_price = models.DecimalField("prix unitaire", max_digits=12, decimal_places=3, default=0)

    @property
    def subtotal(self):
        return self.quantity * self.unit_price

    def __str__(self):
        return f"{self.description} x{self.quantity}"


class Payment(models.Model):
    """A payment recorded against an invoice."""

    class Method(models.TextChoices):
        CASH = "cash", "Espèces"
        CHECK = "check", "Chèque"
        TRANSFER = "transfer", "Virement"

    invoice = models.ForeignKey(Invoice, on_delete=models.CASCADE, related_name="payments")
    amount = models.DecimalField("montant", max_digits=12, decimal_places=3)
    method = models.CharField(max_length=20, choices=Method.choices, default=Method.CASH)
    paid_on = models.DateField("date du paiement", default=today)
    note = models.CharField(max_length=200, blank=True)

    class Meta:
        ordering = ["-paid_on"]

    def __str__(self):
        return f"{self.amount} ({self.get_method_display()})"


class Reminder(models.Model):
    """A payment reminder, generated by the daily job or sent manually."""

    class Channel(models.TextChoices):
        SMS = "sms", "SMS"
        CALL = "call", "Appel"
        WHATSAPP = "whatsapp", "WhatsApp"

    invoice = models.ForeignKey(Invoice, on_delete=models.CASCADE, related_name="reminders")
    created_at = models.DateTimeField(auto_now_add=True)
    days_overdue = models.IntegerField(default=0)
    channel = models.CharField(max_length=20, choices=Channel.choices, default=Channel.SMS)
    sent = models.BooleanField(default=False)
    sent_at = models.DateTimeField(null=True, blank=True)
    message = models.TextField(blank=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"Rappel {self.invoice.number} (J+{self.days_overdue})"
